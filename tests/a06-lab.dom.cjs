'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),vm=require('node:vm');
const {JSDOM,VirtualConsole}=require('jsdom');
const root=path.resolve(__dirname,'..'),lab=path.join(root,'lab/a06/index.html');
const html=fs.readFileSync(lab,'utf8');
assert.ok(!/supabase\.co|service_role|auth\.signIn|shared-trips\.js|localStorage|sessionStorage|navigator\.serviceWorker/i.test(html),'Lab must not use real data/access');
assert.ok(html.includes('Aucun compte Supabase')&&html.includes('Données de démonstration'));
assert.ok(html.indexOf('</head>')<html.indexOf('a06-panel.js'),'assistant must load after DOM body');
const vconsole=new VirtualConsole(),errors=[];
vconsole.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM(html,{url:'https://lab.example.invalid/lab/a06/',runScripts:'outside-only',virtualConsole:vconsole,pretendToBeVisual:true});
const w=dom.window,context=dom.getInternalVMContext();
w.scrollTo=()=>{};w.matchMedia=()=>({matches:true});
w.HTMLElement.prototype.scrollIntoView=()=>{};
w.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','')};
w.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open')};
w.fetch=()=>{throw Error('Forbidden network from synthetic Lab')};
w.XMLHttpRequest=class{open(){throw Error('Forbidden XHR')}};
w.localStorage.setItem('protected-trip-data','do-not-touch');
for(const script of w.document.querySelectorAll('script')){
 const src=script.getAttribute('src');
 if(src){
  const file=path.resolve(path.dirname(lab),src);
  assert.ok(file.startsWith(path.resolve(root,'dist')+path.sep),'Only frozen local A06 modules allowed: '+src);
  vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:path.basename(file)});
 }else vm.runInContext(script.textContent,context,{filename:'lab-inline.js'});
}
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
(async()=>{
 assert.equal(w.A06Lab.stats().placeCount,83);
 assert.equal(w.A06Lab.stats().backend,'none');
 assert.equal(w.A06Lab.stats().persistence,'none');
 assert.equal(w.document.querySelectorAll('.poi').length,24,'Lab lists public catalogue sample');
 assert.ok(w.document.querySelector('#a06-open'));
 const api=w.A06TourismAssistant;
 const info=await api.ask('Que voir à Bari ?','fr');
 assert.equal(info.knowledgeSource,'puglia-structured-0.4');
 assert.equal(info.language,'fr');
 assert.equal(api.stats().poiStaticReviewed,45);
 assert.equal(api.stats().poiSourceLinkedDrafts,21);
 assert.equal(api.stats().operatorSitesReviewed,10);
 assert.ok(info.text.length>50);
 const route=w.A06RouteProposals.propose('Propose-moi un parcours autour de Bari','fr');
 assert.equal(route.ok,true);
 assert.ok(route.stops.length>=2);
 assert.ok(route.stops.every(p=>!p.plannerId.startsWith('spa-')&&!p.plannerId.startsWith('boat-')));
 const ctx=w.A06PlannerCatalog.proposalContext();
 assert.equal(ctx.canEdit,true);
 assert.equal(w.A06PlannerCatalog.openNativeAdd(route.stops[0].plannerId,ctx.fingerprint).ok,true);
 assert.ok(w.document.querySelector('#lab-dialog').hasAttribute('open'));
 assert.equal(w.A06Lab.stats().stops.length,0,'opening modal cannot write');
 w.document.querySelector('#lab-confirm').click();
 assert.equal(w.A06Lab.stats().stops.length,1,'second click explicitly adds synthetic stop');
 assert.equal(w.localStorage.getItem('protected-trip-data'),'do-not-touch');
 w.document.querySelector('#lab-role').value='read';
 w.document.querySelector('#lab-role').dispatchEvent(new w.Event('change',{bubbles:true}));
 const read=w.A06PlannerCatalog.proposalContext();
 assert.equal(read.canEdit,false);
 assert.equal(w.A06PlannerCatalog.openNativeAdd(route.stops[1].plannerId,read.fingerprint).ok,false);
 assert.equal(w.A06Lab.stats().stops.length,1);
 const card=w.document.querySelector('#a06-open');card.click();
 const question=w.document.querySelector('#a06-panel .a06-input');
 question.value='Que voir à Bari ?';
 w.document.querySelector('#a06-panel form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 for(let i=0;i<30 && !w.document.querySelector('#a06-panel .a06-matches button');i++)
  await new Promise(resolve=>setTimeout(resolve,10));
 assert.ok(w.document.querySelector('#a06-panel .a06-matches button'));
 assert.equal(w.A06Lab.stats().stops.length,1,'information cannot add a stop');
 assert.equal(errors.length,0,errors.join('; '));
 console.log('PASS Aracne Lab: no Supabase/network/storage, 83 public places, role switch, two-click synthetic add, source statuses and 4-locale modules');
 dom.window.close();
})().catch(err=>{console.error(err);process.exitCode=1});
